"""Generate every figure for the paper.

GOVERNING RULE: figures assert claims, so every number that appears in a
figure is computed at run time -- from the closed forms in
``verify/common.py`` for the theory figures (1-4), and from
``verify/results_report.json`` (itself derived from ``results/*.csv`` by
``verify/analyze_results.py``, never hand-touched) for the one results
figure (5). Nothing here is hand-drawn or hard-coded. Where a figure needs a
derived quantity that has no dedicated closed-form function (e.g. the
propriety-failure crossing point in Figure 3), it is obtained by evaluating
``V.expected_score`` on a grid and reading the crossing off the resulting
arrays -- never by re-deriving or copying a formula from the paper's proofs.

Run:  python figures/make_figures.py
Output: figures/fig{1..5}_*.pdf, figures/fig{1..5}_*.png, figures/captions.md
"""
