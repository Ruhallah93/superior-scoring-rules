import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "verify"))
import common as V  # noqa: E402

RESULTS_REPORT_PATH = HERE.parent / "verify" / "results_report.json"

CAPTIONS_PATH = HERE / "captions.md"

# --------------------------------------------------------------- style (IJAR)
GRAY_DARK = "0.15"
GRAY_MID = "0.45"
GRAY_LIGHT = "0.85"

def apply_style():
    plt.rcParams.update({
        "font.family": "serif",
        "font.size": 9,
        "axes.titlesize": 9,
        "axes.labelsize": 9,
        "xtick.labelsize": 8,
        "ytick.labelsize": 8,
        "legend.fontsize": 8,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "savefig.dpi": 200,
    })

def clean_axes(ax, hide_left=False, hide_bottom=False):
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    if hide_left:
        ax.spines["left"].set_visible(False)
    if hide_bottom:
        ax.spines["bottom"].set_visible(False)

def save_fig(fig, name):
    fig.savefig(HERE / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(HERE / f"{name}.png", bbox_inches="tight", dpi=200)
    plt.close(fig)

_captions = []
def write_caption(name, title, body, ids):
    ids_str = ", ".join(ids)
    _captions.append(f"## {title} (`{name}`)\n\n{body}\n\n<!-- ids: {ids_str} -->\n")

def flush_captions():
    header = (
        "<!-- GENERATED by figures/make_figures.py -- do not edit by hand. -->\n"
        "# Figure captions\n\n"
    )
    CAPTIONS_PATH.write_text(header + "\n".join(_captions), encoding="utf-8")


