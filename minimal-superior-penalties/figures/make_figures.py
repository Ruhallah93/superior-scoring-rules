def fig1_overlap():
    """The paper in one image: the correct-range/incorrect-range overlap at
    c = 13, and lambda* as the width that closes it."""
    c = 13
    sup_psi = V.sup_psi_brier(c)
    inf_xi = V.inf_xi_brier(c)
    lam_star = V.lambda_star_brier(c)
    assert abs((sup_psi - inf_xi) - lam_star) < 1e-12, "sup_psi - inf_xi must equal lambda*"

    fig, ax = plt.subplots(figsize=(3.2, 1.7))

    y_correct, y_incorrect = 1.0, 0.0
    bar_lw = 5

    x_display_end = sup_psi + 1.35 * lam_star  # room to show the hatched bar continuing

    # correct range: solid bar [0, sup_psi]
    ax.plot([0, sup_psi], [y_correct, y_correct], color="black", lw=bar_lw,
             solid_capstyle="butt", zorder=3)
    ax.text(sup_psi / 2, y_correct + 0.22, r"correct range $[0,\ \Sigma_\psi]$",
             ha="center", va="bottom", fontsize=8)

    # incorrect range: hatched bar [inf_xi, ->), drawn out to x_display_end
    ax.barh(y_incorrect, x_display_end - inf_xi, left=inf_xi, height=0.16,
             facecolor="white", edgecolor="black", hatch="////", lw=1.0, zorder=3)
    ax.annotate("", xy=(x_display_end + 0.05, y_incorrect),
                 xytext=(x_display_end, y_incorrect),
                 arrowprops=dict(arrowstyle="-|>", color="black", lw=1.0))
    ax.text((inf_xi + x_display_end) / 2, y_incorrect - 0.22,
             r"incorrect range $[\Sigma_\xi,\ \to)$", ha="center", va="top", fontsize=8)

    # overlap shading
    ax.axvspan(inf_xi, sup_psi, color=GRAY_LIGHT, zorder=1)

    # double arrow spanning the overlap, labelled lambda*
    y_arrow = 0.5
    ax.annotate("", xy=(sup_psi, y_arrow), xytext=(inf_xi, y_arrow),
                 arrowprops=dict(arrowstyle="<->", color="black", lw=0.9), zorder=4)
    ax.text((inf_xi + sup_psi) / 2, y_arrow + 0.08, r"$\lambda^\ast$",
             ha="center", va="bottom", fontsize=9)

    ax.set_xlim(-0.03, x_display_end + 0.18)
    ax.set_ylim(-0.55, 1.55)
    ax.set_yticks([])
    ax.set_xticks([0, inf_xi, sup_psi])
    ax.set_xticklabels([f"{0:.0f}", f"{inf_xi:.3f}", f"{sup_psi:.3f}"])
    ax.set_xlabel("sum-form Brier score, $c=13$")
    clean_axes(ax, hide_left=True)

    save_fig(fig, "fig1_overlap")
    write_caption(
        "fig1_overlap", "Figure 1: the overlap that superiority closes",
        "The range of sum-form Brier scores attainable on correctly classified "
        f"forecasts, $[0, \\Sigma_\\psi]$, and on incorrectly classified ones, "
        f"$[\\Sigma_\\xi, \\to)$, at $c=13$. The two ranges overlap "
        f"(shaded); the overlap has width $\\lambda^\\ast=\\Sigma_\\psi-\\Sigma_\\xi="
        f"{lam_star:.4f}$, the minimal penalty that separates them. "
        f"$\\Sigma_\\psi={sup_psi:.4f}$ and $\\Sigma_\\xi={inf_xi:.4f}$ are computed "
        "via `V.sup_psi_brier(13)` and `V.inf_xi_brier(13)`; the hatched bar is "
        "drawn open-ended since the incorrect range is unbounded above.",
        ids=["T1", "T2", "T6"],
    )


