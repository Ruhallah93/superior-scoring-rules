def fig6_primary_comparison_cells():
    """Per-cell macro-F1 differences (supercritical minus published), one
    dot per (dataset, regime) cell, for both bases -- makes concrete what
    Table 10's aggregate mean/median/CI are aggregating over, the same way
    fig5 makes the frontier concrete rather than schematic. Data comes
    entirely from verify/results_report.json's primary_comparison_cell_level
    and primary_comparison_cell_level_confirmatory_n8 blocks (themselves
    derived from results/*.csv by verify/analyze_results.py) -- the same
    source Table 10's own numbers come from, so nothing here can drift out
    of sync with the table.
    """
    if not RESULTS_REPORT_PATH.exists():
        raise FileNotFoundError(
            f"{RESULTS_REPORT_PATH} not found -- run `python verify/analyze_results.py` "
            "first; fig6 refuses to draw from anything but that file."
        )
    report = json.loads(RESULTS_REPORT_PATH.read_text(encoding="utf-8"))

    # Cell display order matches Table 9's own dataset-then-regime grouping
    # (mnist block, then cifar10 block, then the exploratory emnist_balanced
    # cell last) rather than the JSON's alphabetical order, so a reader
    # comparing this figure against Table 9 finds the same cells in the
    # same places.
    cell_order = ["mnist/full", "mnist/subset", "mnist/noisy", "mnist/hard",
                  "cifar10/full", "cifar10/subset", "cifar10/noisy", "cifar10/hard",
                  "emnist_balanced/full"]
    exploratory_cell = "emnist_balanced/full"

    fig, axes = plt.subplots(1, 2, figsize=(5.2, 2.9), sharey=True)
    y_cells = np.arange(len(cell_order))[::-1]  # top row = first cell in cell_order
    y_agg = y_cells[-1] - 1.4  # aggregate row, set apart below the 9 cells

    for ax, base, base_label in zip(axes, ["brier", "log"], ["Brier", "Logarithmic"]):
        pcl = report["primary_comparison_cell_level"][base]
        cell_to_diff = dict(zip(pcl["cells"],
                                 pcl["cell_mean_diffs_star_plus_minus_published"]))

        ax.axvline(0, color="black", lw=0.8, zorder=1)

        for y, cell in zip(y_cells, cell_order):
            is_exploratory = (cell == exploratory_cell)
            ax.plot([cell_to_diff[cell]], [y],
                     marker=("D" if is_exploratory else "o"),
                     color=(GRAY_MID if is_exploratory else "black"),
                     markersize=5, zorder=4)

        n8 = report["primary_comparison_cell_level_confirmatory_n8"][base]
        lo, hi = n8["ci95_t"]
        ax.plot([lo, hi], [y_agg, y_agg], color="black", lw=1.3, zorder=3)
        ax.plot([n8["mean_diff"]], [y_agg], marker="D", color="black",
                 markersize=5.5, zorder=5)

        ax.set_title(base_label, fontsize=8.5)
        ax.set_xlabel("macro-F1 diff.\n(supercritical $-$ published)", fontsize=7)
        ax.tick_params(axis="y", length=0)
        clean_axes(ax, hide_left=True)

    axes[0].set_yticks(list(y_cells) + [y_agg])
    axes[0].set_yticklabels(
        [c.replace("emnist_balanced", "emnist\\_bal.") for c in cell_order]
        + ["$n=8$ mean, 95\\% $t$-CI"], fontsize=7)

    save_fig(fig, "fig6_primary_comparison_cells")
    write_caption(
        "fig6_primary_comparison_cells",
        "Figure 6: what Table 10's aggregate is aggregating over",
        "Cell-level macro-F1 difference (supercritical minus published) for "
        "each of the nine (dataset, regime) cells, both bases. Circles are "
        "the eight confirmatory cells (mnist and cifar10, four regimes "
        "each); the diamond is the exploratory emnist\\_balanced/full cell, "
        "added afterward by Amendment 1 and not pooled into the primary "
        "statistic. The bottom row shows the confirmatory ($n=8$) mean "
        "difference with its 95% $t$-interval, the same numbers Table 10 "
        "reports. Both intervals straddle zero; most individual cells are "
        "exactly tied (difference $0$) or favour published by a small "
        "margin, consistent with the paper's own reading of this comparison "
        "as inconclusive rather than a demonstrated improvement. Data: "
        "`verify/results_report.json`, generated by `verify/analyze_results.py`.",
        ids=["R1", "R2"],
    )


